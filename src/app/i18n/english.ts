export function translateEnglish(text: string): string {
  if (ENGLISH[text]) return ENGLISH[text];
  const rules: [RegExp, (...parts: string[]) => string][] = [
    [/^(\d+) 位摘要$/, (bits) => `${bits}-bit digest`],
    [
      /^(.+) 密钥必须为 (.+) 字节（当前 (\d+) 字节）。$/,
      (algorithm, sizes, actual) =>
        `${algorithm} key must contain ${sizes} bytes (received ${actual} bytes).`,
    ],
    [/^IV 必须为 (\d+) 字节。$/, (bytes) => `IV must contain ${bytes} bytes.`],
    [
      /^密文长度必须为 (\d+) 字节的整数倍。$/,
      (bytes) => `Ciphertext length must be a multiple of ${bytes} bytes.`,
    ],
    [
      /^无填充模式要求输入长度为 (\d+) 字节的整数倍。$/,
      (bytes) => `Without padding, input length must be a multiple of ${bytes} bytes.`,
    ],
    [
      /^RSA 明文最多 (\d+) 字节，当前 (\d+) 字节；不支持自动分段。$/,
      (limit, actual) =>
        `RSA plaintext is limited to ${limit} bytes (received ${actual} bytes). Automatic splitting is not supported.`,
    ],
    [/^RSA 密文必须为 (\d+) 字节。$/, (bytes) => `RSA ciphertext must contain ${bytes} bytes.`],
  ];
  for (const [pattern, render] of rules) {
    const match = text.match(pattern);
    if (match) return render(...match.slice(1));
  }
  return text;
}
